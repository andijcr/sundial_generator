export function makeT(lang) {
  const d = STRINGS[lang] || STRINGS.en;
  return (key, ...args) => {
    let s = key in d ? d[key] : (STRINGS.en[key] ?? key);
    if (typeof s === 'string' && args.length) s = s.replace(/\{(\d)\}/g, (_, i) => args[+i]);
    return s;
  };
}
